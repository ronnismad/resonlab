export function applyPreset(stateFactory, preset) {
  const base = stateFactory(preset.resonatorType);
  return {
    ...base,
    projectName: preset.name,
    resonatorType: preset.resonatorType,
    environment: { ...base.environment, ...(preset.environment || {}) },
    geometry: { ...base.geometry, ...(preset.geometry || {}) },
    inverseDesign: { ...base.inverseDesign, ...(preset.inverseDesign || {}) },
    couplingSweep: { ...base.couplingSweep, ...(preset.couplingSweep || {}) },
    science: { ...base.science, ...(preset.science || {}) },
    display: { ...base.display, tab: 'geometry' },
    presetId: preset.id,
    presetExperiment: preset.experiment,
    validation: { errors: {}, warnings: {} },
  };
}

export function getPreset(id) {
  return DEFAULT_PRESETS.find((p) => p.id === id) || null;
}

/** Localized preset label/experiment (EN/RU). */
export function presetLabel(p, lang = 'en') {
  if (!p) return '';
  return (lang === 'ru' && p.nameRu) ? p.nameRu : p.name;
}
export function presetExperiment(p, lang = 'en') {
  if (!p) return '';
  return (lang === 'ru' && p.experimentRu) ? p.experimentRu : p.experiment;
}
